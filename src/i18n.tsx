// ---- Question-level translations -------------------------------------------
// Questions store language variants under `translations`. The base `text` /
// `options` / `correctAnswer` / `category` / `difficulty` / `explanation` are
// treated as the source (Uzbek) truth; the maps below let a Question forward to
// its translated copy when a language is active.
export interface QuestionTranslation {
  text: string;
  options?: string[];
  correctAnswer: string;
  category?: string;
  difficulty?: string;
  explanation?: string;
}

export const getQuestionInLanguage = <T extends { translations?: Record<Language, QuestionTranslation> }>(
  q: T,
  lang: Language
): T => {
  // Default to the base (Uzbek) content when there is no translation or the
  // language matches the source.
  if (lang === 'uz' || !q || !q.translations || !q.translations[lang]) return q;
  return { ...q, ...q.translations[lang] } as T;
};

export const translateDiplicity = (d: string | undefined | null, lang: Language): string => {
  const m: Record<Language, Record<string, string>> = {
    uz: { Oson: 'Oson', "O'rta": "O'rta", Qiyin: 'Qiyin' },
    ru: { Oson: 'Легкий', "O'rta": 'Средний', Qiyin: 'Сложный' },
    en: { Oson: 'Easy', "O'rta": 'Medium', Qiyin: 'Hard' },
  };
  if (!d) return d || '';
  return (m[lang] && m[lang][d]) || d;
};

